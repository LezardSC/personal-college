from tools.scholarship import documents as d
from tools.scholarship import work as w
from tools.tests.helpers import D0, SEQUENCE, WithState, graded


class TestAgenda(WithState):
    def agenda(self):
        return d.agenda(self.state, SEQUENCE, D0)

    def test_agenda_keeps_creation_order(self):
        w.add_work(self.state, "LAB1.2", "lab", "M1", "Second", "a", D0, self.rules, hours=10)
        w.add_work(self.state, "HW1.1", "homework", "M1", "First", "a", D0, self.rules, hours=2)
        text = self.agenda()
        self.assertLess(text.index("LAB1.2"), text.index("HW1.1"))

    def test_agenda_shows_hours(self):
        w.add_work(self.state, "HW1.1", "homework", "M1", "T", "a", D0, self.rules, hours=4)
        self.assertIn("| 4 |", self.agenda())

    def test_agenda_next_step_and_graded(self):
        graded(self.state, self.rules, "LAB1.1", "lab", "M1", 13)
        text = self.agenda()
        self.assertIn("L1.01", text)
        self.assertIn("## Recently graded", text)
        self.assertIn("13", text)
        self.assertIn("feedback/LAB1.1-v1.md", text)

    def test_agenda_nothing_to_submit(self):
        self.assertIn("Nothing to submit", self.agenda())

    def test_agenda_announces_exam(self):
        for id in ("L1.01", "L1.02", "L2.01"):
            w.step_done(self.state, id)
        text = self.agenda()
        self.assertIn("Exam to take", text)
        self.assertIn("`/lesson`", text)

    def test_agenda_oral_exam_names_oral(self):
        for id in ("L1.01", "L1.02", "L2.01", "EXAM-WRITTEN-S1"):
            w.step_done(self.state, id)
        self.assertIn("`/oral`", self.agenda())

    def test_agenda_blocked(self):
        w.add_work(self.state, "LAB1.1", "lab", "M1", "T", "a", D0, self.rules, hours=2)
        self.assertIn("`/lesson` is blocked", self.agenda())

    def test_agenda_has_generated_header(self):
        self.assertTrue(self.agenda().startswith("<!-- Generated by `python3 tools/college.py agenda`"))


class TestTranscript(WithState):
    def transcript(self):
        return d.transcript(self.state, SEQUENCE, self.rules)

    def test_transcript_dash_when_empty(self):
        text = self.transcript()
        self.assertIn("M1", text)
        self.assertIn("Average: —", text)

    def test_transcript_grades_and_provisional(self):
        graded(self.state, self.rules, "LAB1.1", "lab", "M1", 14.5)
        text = self.transcript()
        self.assertIn("14.5", text)
        self.assertIn("provisional", text)

    def test_transcript_verdicts(self):
        graded(self.state, self.rules, "LAB1.1", "lab", "M1", 8)
        self.assertIn("not passed", self.transcript())

    def test_transcript_headings(self):
        text = self.transcript()
        self.assertIn("## Semester 1 — average:", text)
        self.assertIn("### Exams and orals S1", text)
