"""Generated Markdown documents: the agenda and the transcript."""
import re
from datetime import date

from tools.scholarship.averages import module_average, module_complete, semester_average, semester_modules
from tools.scholarship.program import EXAMS
from tools.scholarship.status import status
from tools.scholarship.work import PASS_MARK, best_grade

WARNING = "<!-- Generated by `python3 tools/college.py agenda`: do not edit by hand. -->"


def _fmt(n: float | None) -> str:
    return "—" if n is None else f"{n:g}"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _verdict(average: float | None) -> str:
    return "" if average is None else (" — passed" if average >= PASS_MARK else " — not passed")


def agenda(state: dict, sequence: list[dict], today: date, rules: dict) -> str:
    st = status(state, sequence, rules)
    lines = [WARNING, "# Agenda", "", f"*Updated on {today.isoformat()}.*", "", "## To do", ""]
    todo = [i for i in state["work"].values() if i["status"] == "todo"]
    if todo:
        lines += ["| Id | Type | Title | Hours | Blocking | Assignment |", "|---|---|---|---|---|---|"]
        for i in todo:
            lines.append(f"| {i['id']} | {i['type']} | {_cell(i['title'])} | {i['hours']:g} "
                         f"| {'yes' if i['blocking'] else 'no'} | [{i['assignment']}]({i['assignment']}) |")
    else:
        lines.append("Nothing to submit right now.")
    if st["being_graded"]:
        lines += ["", f"Being graded: {', '.join(st['being_graded'])}."]

    lines += ["", "## Next step", ""]
    step = st["next_step"]
    if st["course_complete"]:
        lines.append("Course complete. Congratulations!")
    elif step is None:
        lines.append("No program loaded (`program/sequence.json` missing or empty).")
    else:
        lines.append(f"**{step['id']}** — {step['title']} ({step['type']}, {step['module']}).")
        if not st["can_advance"]:
            if st["blocking"]:
                lines += ["", "`/lesson` is blocked until the blocking items above are submitted."]
            else:
                lines += ["", f"A resit is required ({', '.join(st['resits_required'])}); "
                              "it will be started at the next `/lesson`."]
        elif st["exam_to_take"]:
            command = "/oral" if step["type"] == "oral-exam" else "/lesson"
            graded_note = " — paper being graded" if st["exam_to_take"] in st["being_graded"] else ""
            lines += ["", f"**Exam to take**: run `{command}` when you are ready{graded_note}."]

    lines += ["", "## Resits", ""]
    resits = [i for i in state["work"].values() if i["type"] == "resit"]
    if st["resits_required"]:
        lines.append(f"Resit coming for: {', '.join(st['resits_required'])} (started at the next `/lesson`).")
    for i in resits:
        lines.append(f"- {i['id']}: {i['status']} — grade {_fmt(best_grade(i))}")
    if not st["resits_required"] and not resits:
        lines.append("None.")

    lines += ["", "## Recently graded", ""]
    graded = [(a, i) for i in state["work"].values() for a in i["attempts"] if a["grade"] is not None]
    graded.sort(key=lambda x: x[0]["date"], reverse=True)
    if graded:
        for a, i in graded[:5]:
            lines.append(f"- {a['date']} · **{i['id']}** {i['title']}: **{_fmt(a['grade'])}/20** "
                         f"— [{a['feedback']}]({a['feedback']})")
    else:
        lines.append("Nothing yet.")
    return "\n".join(lines) + "\n"


def _work_table(items: list[dict]) -> list[str]:
    if not items:
        return ["*No graded work yet.*"]
    lines = ["| Id | Title | Grade /20 | Coef | Attempts | Feedback |", "|---|---|---|---|---|---|"]
    for i in sorted(items, key=lambda i: i["id"]):
        grades = " / ".join(_fmt(a["grade"]) for a in i["attempts"]) or "—"
        last = next((a["feedback"] for a in reversed(i["attempts"]) if a["feedback"]), None)
        link = f"[{last}]({last})" if last else "—"
        lines.append(f"| {i['id']} | {_cell(i['title'])} | {_fmt(best_grade(i))} | {i['coef']:g} | {grades} | {link} |")
    return lines


def transcript(state: dict, sequence: list[dict], rules: dict) -> str:
    lines = [WARNING, "# Transcript", ""]
    semesters = list(dict.fromkeys(s["semester"] for s in sequence))
    for sem in semesters:
        average, provisional = semester_average(state, sequence, sem, rules)
        mention = " (provisional)" if provisional and average is not None else ""
        number = re.fullmatch(r"S(\d+)", sem).group(1)
        lines += [f"## Semester {number} — average: {_fmt(average and round(average, 2))}{mention}"
                  f"{_verdict(average)}", ""]
        for module in semester_modules(sequence, sem):
            avg = module_average(state, module)
            verdict = _verdict(avg)
            if avg is not None and not module_complete(state, sequence, module, rules):
                verdict += " (in progress)"
            items = [i for i in state["work"].values() if i["module"] == module and i["type"] != "reading"]
            lines += [f"### {module}", "", f"Average: {_fmt(avg and round(avg, 2))}{verdict}", ""] \
                + _work_table(items) + [""]
        exams = [i for i in state["work"].values()
                 if i["module"] == sem and i["type"] in EXAMS + ("mock-oral",)]
        lines += [f"### Exams and orals {sem}", ""] + _work_table(exams) + [""]
    known = {s["module"] for s in sequence} | set(semesters)
    outside = [i for i in state["work"].values() if i["module"] not in known and i["type"] != "reading"]
    if not sequence and not outside:
        lines.append("*No program loaded.*")
    if outside:
        lines += ["## Outside the program", ""]
        for module in dict.fromkeys(i["module"] for i in outside):
            avg = module_average(state, module)
            lines += [f"### {module}", "", f"Average: {_fmt(avg and round(avg, 2))}{_verdict(avg)}", ""]
            lines += _work_table([i for i in outside if i["module"] == module]) + [""]
    return "\n".join(lines)
